#!/usr/bin/env bash
# ============================================================================
# Cubeful-money mEMG — reproduction script
# ----------------------------------------------------------------------------
# Computes cubeful-money mEMG (mean error per move, milli-equity, judged by
# gnubg at N-ply) for the engines, playing LIVE-CUBE money games (Jacoby):
#       PureTD 4L-cubeful (ours)      gnubg 1.08 (gnubg-ext)       Open Sage
# Unlike the cubeless table, games are played with a real cube (doubles/takes/
# drops), and gnubg scores BOTH chequer and cube decisions. Report the chequer
# mEMG (move quality) and overall (chequer+cube); cube mEMG is high-variance.
#
# All real logic lives in the codebase; this file is just the invocations + combine:
#   run_cubeful_memg.py      ours(4L cubeful) + gnubg-ext: play_and_record_cubeful
#                            (Jacoby) -> export_mat(money_game=True) -> gnubg
#                            N-ply (chequer+cube, cubeful) -> bootstrap CIs.
#   experiments/offline_analysis/sage_money_memg.py
#                            Open Sage: scores Sage's OWN money self-play
#                            transcripts (generated by bgsage, Jacoby+Beaver on)
#                            with the SAME gnubg N-ply judge. Run separately
#                            because Sage games come from its native generator.
#
# Prerequisites:
#   gnubg 1.08.003 CLI at /usr/games/gnubg  (apt-get install -y gnubg; or set
#                                          GNUBG_CMD — judge AND gnubg-ext players)
#   pip install bgsage                    (Open Sage; needs AVX2) + Sage transcripts
#   torch + this repo; model best_models/cubeful_money_512_512_256_256.pt
#
# Caveats to disclose (see the two-agent review notes): runs are not seeded / no
# common-random-numbers across engines; Sage transcripts are generated with
# Beaver on while ours/gnubg in-process self-play has no beaver. Set workers to
# PHYSICAL core count (gnubg N-ply is compute-bound; SMT/oversubscription hurts).
# ============================================================================
set -euo pipefail
cd "$(dirname "$0")/../.."                    # repo root

# OUT must be a fresh directory per campaign: the per-game writer APPENDS,
# so reusing a directory silently pools new games onto old ones.
OUT="${OUT:-/tmp/cubeful_memg_repro}"
GAMES="${GAMES:-4000}"
PLIES="${PLIES:-4}"
PLAY_WORKERS="${PLAY_WORKERS:-48}"            # = PHYSICAL cores (not SMT threads)
GNUBG_WORKERS="${GNUBG_WORKERS:-48}"          # = PHYSICAL cores; N-ply scales ~1/core
CHUNK="${CHUNK:-2}"                           # small chunks isolate the 4-ply heavy tail

# --- ours (4L cubeful) + gnubg-ext, live-cube money self-play, gnubg-judged ---
python3 experiments/offline_analysis/run_cubeful_memg.py \
    --players ours-0ply,ours-1ply,gnubg-ext-0ply,gnubg-ext-1ply \
    --games "$GAMES" --plies "$PLIES" --chunk "$CHUNK" \
    --play-workers "$PLAY_WORKERS" --gnubg-workers "$GNUBG_WORKERS" \
    --save-pergame "$OUT"

# --- Open Sage 1-ply (cube-aware analyzer self-play; needs bgsage) ----------
# SAGE_UNPRUNED=1 reproduces the PUBLISHED paper-convention row (2.258); drop
# the env var and you are measuring Sage's production filter instead.
SAGE_UNPRUNED=1 python3 experiments/offline_analysis/run_cubeful_memg.py \
    --players sage-analyzer-1ply \
    --games "$GAMES" --plies "$PLIES" --chunk "$CHUNK" \
    --play-workers "$PLAY_WORKERS" --gnubg-workers "$GNUBG_WORKERS" \
    --save-pergame "$OUT"

# --- process output: pooled equal-n table (chequer/cube/overall, bootstrap CIs) ---
python3 experiments/offline_analysis/run_cubeful_memg.py --combine "$OUT"

# The sage-analyzer-0ply row is scored from pooled raw shards via
# sage_money_memg.py (transcript path) — see cubeful_memg/README.md.
